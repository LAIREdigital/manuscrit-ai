#!/usr/bin/env node
// Crawl a site's sitemap into a knowledge file the Worker bundles.
// Usage: node chatbot/scripts/crawl.mjs <site-id> <https://domain> [maxPages]
// Writes chatbot/clients/<site-id>.crawl.js. Re-run to refresh, then redeploy.

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SKIP = /\/(tag|tags|author|page|category|wp-json|feed|_hcms|hs-fs|hubfs)\/|\.(pdf|jpg|png|gif|svg|zip|xml)$/i;

export function htmlToText(html) {
  const title = (html.match(/<title[^>]*>([\s\S]*?)<\/title>/i) || [])[1] || "";
  const main = (html.match(/<main[\s\S]*?<\/main>/i) || [html])[0];
  const text = main
    .replace(/<(script|style|noscript|svg|nav|header|footer|form|iframe)[\s\S]*?<\/\1>/gi, " ")
    .replace(/<(h[1-6]|p|li|br|div|section|tr)[^>]*>/gi, "\n")
    .replace(/<[^>]+>/g, " ")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&#39;|&rsquo;|&lsquo;/g, "'")
    .replace(/&quot;|&ldquo;|&rdquo;/g, '"')
    .replace(/&[a-z]+;|&#\d+;/gi, " ")
    .replace(/[ \t]+/g, " ")
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l.length > 2)
    .join("\n");
  return { title: decode(title.trim()), text };
}

const decode = (s) => s.replace(/&amp;/g, "&").replace(/&#39;|&rsquo;/g, "'").replace(/&[a-z]+;/gi, " ");

export function locs(xml) {
  return [...xml.matchAll(/<loc>\s*([^<\s]+)\s*<\/loc>/g)].map((m) => m[1].replace(/&amp;/g, "&"));
}

async function get(url) {
  const res = await fetch(url, { headers: { "User-Agent": "LAIRE-chat-crawler/1.0" } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.text();
}

async function pageUrls(base) {
  const queue = [`${base}/sitemap.xml`];
  const pages = new Set();
  const seen = new Set();
  while (queue.length) {
    const sm = queue.shift();
    if (seen.has(sm)) continue;
    seen.add(sm);
    const xml = await get(sm).catch(() => "");
    for (const u of locs(xml)) (u.endsWith(".xml") ? queue : { push: (x) => pages.add(x) }).push(u);
  }
  return [...pages].filter((u) => !SKIP.test(u));
}

async function main() {
  const [id, rawBase, max = "60"] = process.argv.slice(2);
  if (!id || !rawBase) {
    console.error("Usage: node chatbot/scripts/crawl.mjs <site-id> <https://domain> [maxPages]");
    process.exit(1);
  }
  const base = rawBase.replace(/\/$/, "");
  // Service and about pages first, blog posts fill the rest.
  const all = await pageUrls(base);
  const urls = [...all.filter((u) => !/\/blog\//.test(u)), ...all.filter((u) => /\/blog\//.test(u))].slice(0, Number(max));
  if (!urls.length) urls.push(base);
  const parts = [];
  for (const u of urls) {
    try {
      const { title, text } = htmlToText(await get(u));
      if (text.length > 200) parts.push(`# ${title || u}\nSource: ${u}\n${text.slice(0, 6000)}`);
      console.log("ok", u);
    } catch (e) {
      console.log("skip", e.message);
    }
  }
  const out = fileURLToPath(new URL(`../clients/${id}.crawl.js`, import.meta.url));
  const header = `// Generated by chatbot/scripts/crawl.mjs from ${base} on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.\n`;
  await writeFile(out, `${header}export default ${JSON.stringify(parts.join("\n\n"))};\n`);
  console.log(`wrote ${parts.length} pages to ${out}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
